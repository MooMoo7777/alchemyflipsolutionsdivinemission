create table if not exists public.interest_forms (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null check (char_length(name) between 2 and 120),
  email text not null,
  goal text not null,
  status text not null default 'new'
);
alter table public.interest_forms enable row level security;
create policy "anonymous may submit interest" on public.interest_forms for insert to anon with check (true);
create policy "authenticated staff may read interest" on public.interest_forms for select to authenticated using (true);
